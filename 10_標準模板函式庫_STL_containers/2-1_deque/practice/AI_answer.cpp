#include<deque>
#include<iostream>
#include<string>
#include<algorithm>
#include<numeric>
#include<stdexcept>
using namespace std;

int main(){
    // 1. 建立空的deque<string>
    deque<string> patients;

    // 2. 依序push_back三位一般病患
    patients.push_back("王小明");
    patients.push_back("陳美麗");
    patients.push_back("林大同");

    cout << "【步驟2】目前病患: ";
    for (const string& p : patients) cout << p << ' ';
    cout << endl;
    // 輸出: 【步驟2】目前病患: 王小明 陳美麗 林大同

    // 3. 緊急病患用push_front插隊
    patients.push_front("張醫生的家屬");

    cout << "【步驟3】目前病患: ";
    for (const string& p : patients) cout << p << ' ';
    cout << endl;
    // 輸出: 【步驟3】目前病患: 張醫生的家屬 王小明 陳美麗 林大同

    // 4. 將"陳美麗"移動到index=1
    auto it = find(patients.begin(), patients.end(), "陳美麗");
    if (it != patients.end()){
        patients.erase(it);                          // 先刪除原本位置的"陳美麗"
        patients.insert(patients.begin()+1, "陳美麗"); // 再插入到index=1
    }

    cout << "【步驟4】目前病患: ";
    for (const string& p : patients) cout << p << ' ';
    cout << endl;
    // 輸出: 【步驟4】目前病患: 張醫生的家屬 陳美麗 王小明 林大同

    // 5. 印出第一位與最後一位
    cout << "【步驟5】第一位: " << patients.front() << "，最後一位: " << patients.back() << endl;
    // 輸出: 【步驟5】第一位: 張醫生的家屬，最後一位: 林大同

    // 6. 叫號看診，直到剩下2人
    cout << "【步驟6】開始叫號:" << endl;
    while (patients.size() > 2){
        string current = patients.front();
        patients.pop_front();
        cout << "正在為 " << current << " 看診" << endl;
    }
    /*
    輸出:
    【步驟6】開始叫號:
    正在為 張醫生的家屬 看診
    正在為 陳美麗 看診
    */

    cout << "【步驟6】剩餘病患: ";
    for (const string& p : patients) cout << p << ' ';
    cout << endl;
    // 輸出: 【步驟6】剩餘病患: 王小明 林大同

    // 7. 加號病患，並用at()安全存取
    patients.push_back("李四");

    cout << "【步驟7】目前病患: ";
    for (const string& p : patients) cout << p << ' ';
    cout << endl;
    // 輸出: 【步驟7】目前病患: 王小明 林大同 李四

    try {
        cout << "index=5 的病患是: " << patients.at(5) << endl;  // 超出範圍(目前只有3人，合法index為0~2)
    } catch (const std::out_of_range &e) {
        cout << "錯誤：" << e.what() << endl;
        // 輸出: 錯誤：deque::_M_range_check: __n (which is 5)>= this->size() (which is 3)
    }

    // 8. size()與empty()
    cout << "【步驟8】目前佇列人數: " << patients.size() << endl;   // 輸出: 【步驟8】目前佇列人數: 3
    cout << "【步驟8】佇列是否為空: " << patients.empty() << endl;  // 輸出: 【步驟8】佇列是否為空: 0

    // 9. clear()清空
    patients.clear();
    cout << "【步驟9】清空後是否為空: " << patients.empty() << endl;  // 輸出: 【步驟9】清空後是否為空: 1

    // 10. waitTimes排序與加總
    deque<int> waitTimes = {15, 5, 30, 10, 20};
    sort(waitTimes.begin(), waitTimes.end());

    cout << "【步驟10】排序後的等待時間: ";
    for (const int& t : waitTimes) cout << t << ' ';
    cout << endl;
    // 輸出: 【步驟10】排序後的等待時間: 5 10 15 20 30

    int totalWait = accumulate(waitTimes.begin(), waitTimes.end(), 0);
    cout << "【步驟10】總等待時間: " << totalWait << " 分鐘" << endl;
    // 輸出: 【步驟10】總等待時間: 80 分鐘

    return 0;
}

