// ---------- 第一部分: MinStack ----------
class MinStack{
private:
    stack<int> data;  // 存放實際元素
    stack<int> minS;  // 存放對應每一層push當下的「目前最小值」
public:
    void push(int x){
        data.push(x);
        // 若minS為空，或x小於等於目前最小值，則新的最小值就是x
        // 用<=而非<是為了正確處理「重複最小值」的情況(例如最小值被pop掉一次後，還有另一個相同的最小值)
        if (minS.empty() || x <= minS.top()){
            minS.push(x);
        }
        else{
            minS.push(minS.top());  // 最小值不變，重複push目前的最小值，確保data與minS的元素個數永遠一致
        }
    }

    void pop(){
        data.pop();
        minS.pop();
    }

    int top(){
        return data.top();
    }

    int getMin(){
        return minS.top();
    }

    bool empty(){
        return data.empty();
    }

    int size(){
        return data.size();
    }
};


int main(){
    // ---------- 測試 MinStack ----------
    cout<<"===== 測試 MinStack =====\n";

    MinStack ms;
    cout<< ms.empty() <<endl;  // 輸出: 1 (目前是空的)

    ms.push(5);
    ms.push(3);
    ms.push(7);
    ms.push(1);
    // 目前ms(由底至頂): 5 3 7 1
    // 對應的minS(由底至頂): 5 3 3 1

    cout<< ms.top() <<endl;     // 輸出: 1  (頂端元素)
    cout<< ms.getMin() <<endl;  // 輸出: 1  (目前最小值)
    cout<< ms.size() <<endl;    // 輸出: 4

    ms.pop();  // 彈出1，ms(由底至頂): 5 3 7
    cout<< ms.top() <<endl;     // 輸出: 7
    cout<< ms.getMin() <<endl;  // 輸出: 3  (1被彈出後，最小值變回3)

    ms.pop();  // 彈出7，ms(由底至頂): 5 3
    ms.pop();  // 彈出3，ms(由底至頂): 5
    cout<< ms.getMin() <<endl;  // 輸出: 5  (最小值變回5)
    cout<< ms.size() <<endl;    // 輸出: 1
    cout<< ms.empty() <<endl;   // 輸出: 0 (還有一個元素，非空)


}


