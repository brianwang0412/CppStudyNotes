#include <iostream>
#include <vector>
#include <algorithm>
#include <iomanip>
using namespace std;

int main() {
    int n;
    cin >> n;

    vector<int> scores;
    for (int i = 0; i < n; i++) {
        int s;
        cin >> s;
        scores.push_back(s);
    }

    // 2. 新增轉學生成績
    scores.push_back(100);

    // 3. 由高到低排序
    sort(scores.begin(), scores.end(), greater<int>());

    // 4. 刪除最低分（排序後最後一個元素）
    scores.erase(scores.end() - 1);

    // 5. 計算平均分數
    double sum = 0;
    for (int x : scores) sum += x;
    double avg = sum / scores.size();

    cout << "排序後（含轉學生，已刪除最低分）: ";
    for (int x : scores) cout << x << " ";
    cout << endl;

    cout << fixed << setprecision(2);
    cout << "平均分數: " << avg << endl;

    // 6. 使用迭代器輸出
    cout << "迭代器輸出: ";
    for (vector<int>::iterator it = scores.begin(); it != scores.end(); ++it) {
        cout << *it << " ";
    }
    cout << endl;

    // 7. 使用 find 判斷 90 分是否存在
    auto result = find(scores.begin(), scores.end(), 90);
    cout << "90 分是否存在: " << (result != scores.end() ? "存在" : "不存在") << endl;

    // 8. 輸出 size 與 capacity
    cout << "Size: " << scores.size() << ", Capacity: " << scores.capacity() << endl;

    return 0;
}

