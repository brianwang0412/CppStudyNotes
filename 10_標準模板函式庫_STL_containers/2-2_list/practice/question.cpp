/*
======================================================================
《list綜合練習題》—— 診所候診名單管理系統
======================================================================

情境:
某診所使用 std::list<int> 來管理「目前候診中的病患掛號序號」
之所以選用list而非vector/deque，是因為候診名單經常需要：
  - 有病患臨時插隊(在任意位置insert)
  - 有病患臨時取消掛號(在任意位置erase)
  - 兩個診間的候診名單需要合併(splice / merge)
這些操作若用vector/deque實作，插入/刪除中間元素的時間複雜度為O(n)，
而list只要有目標位置的iterator，插入/刪除都是O(1)，因此更適合這種情境。

------------------------------------------------------------
請依序完成以下 Step1 ~ Step13 的操作(請完全依照步驟順序執行，
因為每一步都是基於「前一步執行完的結果」繼續操作，順序錯誤會導致
後面的答案跟著錯誤)。每完成一步，請將list目前的內容印出(元素間以
一個空白分隔，最後換行即可，不要求輸出格式須與範例解答一模一樣，
但「元素順序與數值」必須正確)：

【Step1】建立一個空的 list<int> waitList，並利用 push_back()
         依序新增病患序號: 101, 102, 103, 104, 105

【Step2】有一位病患情況緊急，須「插隊到最前面」，序號為999。
         請使用 insert() (搭配 begin())完成，不可使用push_front()
         (此步驟是為了練習insert()的用法)

【Step3】序號103的病患臨時取消掛號。
         請使用 find() 找到該元素的位置，再用 erase() 刪除
         (不可以直接用remove(103)，此步驟是為了練習find()+erase()的搭配)

【Step4】院方規定「偶數序號」一律要重新掛號，請用 remove_if()
         搭配Lambda表達式，將list中所有「偶數」的序號全部刪除

【Step5】另一個診間的候診名單 waitList2 = {201, 203, 205} 因
         合併診間，需要把waitList2的「全部」病患直接接到waitList
         的尾端。請使用 splice() 完成(不可以用迴圈+push_back())，
         完成後waitList2應變為空
         (提示: splice會直接把節點搬移過去，因此waitList2事後會是空的)

【Step6】現在又有一位病患現場報到，序號為201(注意: 這會與名單中
         既有的201重複)，請用 push_back() 加入這個序號

【Step7】為了方便管理，請用 list 自己的成員函式將waitList「由小到
         大」排序(提醒: list的iterator不支援隨機存取，不能使用
         std::sort(waitList.begin(), waitList.end())，必須使用
         list提供的專屬排序函式)

【Step8】排序後，請將list中「相鄰重複」的序號去除，只保留一個
         (提示: 這正是Step6刻意製造重複201的用意，且該步驟必須
         建立在Step7已排序的基礎上，重複值才會相鄰)

【Step9】有一批VIP的候診序號 vipList = {50, 80}，因為已經事先
         排序好，請直接使用 merge() 將vipList合併進waitList，
         合併後仍要維持「由小到大排序」的狀態，且vipList應變為空

【Step10】因為醫院大螢幕改成「由大到小」倒序叫號顯示，請將
          waitList「反轉」(提示: 使用list自己的成員函式完成，
          效率比<algorithm>的std::reverse()更好)

【Step11】請印出目前waitList的: 第一個元素(front)、最後一個
          元素(back)、目前的病患人數(size)、以及waitList是否為
          空(empty)

【Step12】請計算目前所有候診序號的總和(sum)，以及平均值(avg，
          型別為double)，並將兩者印出
          (提示: sum與avg皆須搭配<numeric>的accumulate()計算)

【Step13】請分別用「正向迭代器(iterator)」與「反向迭代器
          (reverse_iterator)」各遍歷一次waitList並印出結果，
          驗證兩者的輸出應恰好互為顛倒
======================================================================
*/

