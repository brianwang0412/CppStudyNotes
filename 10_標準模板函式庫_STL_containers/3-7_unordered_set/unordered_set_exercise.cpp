#include<unordered_set>  // unordered_set定義在<unordered_set>標頭檔中
#include<iostream>
#include<string>
#include<vector>
#include<algorithm>
#include<numeric>
using namespace std;

/*
======================================================================
《unordered_set綜合練習題》—— 旅遊App「造訪過的城市」記錄系統
======================================================================

情境:
某旅遊App要用 std::unordered_set<string> 來記錄「使用者造訪過的城市」，
由於只在乎「某個城市是否造訪過」，完全不需要排序，且希望查詢/新增的
速度越快越好，因此選用unordered_set(平均O(1))而非set(O(log n))。

------------------------------------------------------------
請依序完成以下 Step1 ~ Step9 的操作(請完全依照順序執行，因為每一步
都是基於「前一步執行完的結果」繼續操作)。每完成一步，請將要求的內容
印出：

【Step1】建立一個空的 unordered_set<string> visited

【Step2】依序使用 insert() 新增以下4筆城市資料(注意其中"Taipei"
         出現了兩次，重複插入應該會失敗、不會真的新增兩筆)：
         "Taipei", "Tokyo", "Taipei", "Osaka"
         完成後請印出目前visited的「元素個數(size)」

【Step3】使用 insert() 新增 "Seoul"，並印出insert()回傳的
         pair<iterator,bool>中的「第二個值(bool)」，驗證這次插入
         是否成功

【Step4】分別使用 count() 印出 "Tokyo" 與 "London" 是否存在於
         visited中(count()結果只會是0或1，因為元素不可重複)

【Step5】使用者不小心刪除了"Osaka"的造訪紀錄，請用 erase(value)
         刪除"Osaka"，並印出erase()的回傳值(實際刪除的筆數)，以及
         刪除後visited的元素個數(size)

【Step6】使用 find() 尋找 "Tokyo" 是否存在，若存在則印出找到的
         城市名稱

【Step7】由於unordered_set不保證遍歷順序，若想要「依字母順序」
         列出目前造訪過的所有城市，請將visited的所有元素複製到一個
         vector<string>中，再用<algorithm>的sort()排序該vector，
         最後印出排序後的結果

【Step8】印出目前visited的 bucket_count()(目前的bucket數量)
         與 load_factor()(目前的負載係數)

【Step9】請搭配 <algorithm> 的 count_if()，計算目前visited中
         「城市名稱字串長度 > 5」的城市有幾個，並印出結果
======================================================================
*/


// ============================ 以下為範例解答 ============================
// 【非常重要的提醒】
// unordered_set的元素「遍歷順序」不受C++標準規範，只與雜湊函式、bucket
// 排列方式有關，與插入順序、字母順序皆無關。以下牽涉到bucket數量、
// load_factor的輸出結果，皆是在特定編譯環境下(g++ 13.3.0, libstdc++,
// x86-64 Linux, C++17)實際測試所得到的結果，换一台電腦或換一個編譯器
// /標準函式庫版本，這些數值都可能不同；但count()、find()、size()、
// erase()等「邏輯上」正確的結果，在任何符合標準的實作下都會是一致的。

int main(){

    // 《Step1》建立空的unordered_set<string>
    unordered_set<string> visited;


    // 《Step2》依序insert()新增4筆城市資料(其中Taipei重複)
    visited.insert("Taipei");
    visited.insert("Tokyo");
    visited.insert("Taipei");  // 重複插入，不會真的新增
    visited.insert("Osaka");

    cout<<"[Step2] size = "<< visited.size() <<endl;
    // 輸出: [Step2] size = 3
    // 解釋: 雖然insert()呼叫了4次，但"Taipei"重複插入失敗(容器內容不變)，
    //      因此實際元素只有Taipei、Tokyo、Osaka共3筆


    // 《Step3》insert()新增"Seoul"，印出回傳pair的bool部分
    auto result = visited.insert("Seoul");
    cout<<"[Step3] insert(Seoul) success = "<< result.second <<endl;
    // 輸出: [Step3] insert(Seoul) success = 1
    // 解釋: "Seoul"原本不存在，插入成功，回傳的pair.second為true(印出1)


    // 《Step4》count()分別查詢"Tokyo"與"London"
    cout<<"[Step4] count(Tokyo)="<< visited.count("Tokyo")
        <<", count(London)="<< visited.count("London") <<endl;
    // 輸出: [Step4] count(Tokyo)=1, count(London)=0
    // 解釋: Tokyo存在(count=1)，London不存在(count=0)


    // 《Step5》erase(value)刪除"Osaka"
    int removed = visited.erase("Osaka");
    cout<<"[Step5] removed="<<removed<<", size="<<visited.size()<<endl;
    // 輸出: [Step5] removed=1, size=3
    // 解釋: Osaka確實存在，刪除成功回傳1；刪除後剩下Taipei、Tokyo、Seoul共3筆


    // 《Step6》find()尋找"Tokyo"
    auto it = visited.find("Tokyo");
    if (it != visited.end()){
        cout<<"[Step6] find(Tokyo) -> "<< *it <<endl;
    }
    // 輸出: [Step6] find(Tokyo) -> Tokyo


    // 《Step7》複製到vector後排序，取得「依字母順序」的結果
    vector<string> sortedCities(visited.begin(), visited.end());
    sort(sortedCities.begin(), sortedCities.end());
    cout<<"[Step7] sorted: ";
    for (const string& c : sortedCities) cout<< c << ' ';
    cout<<endl;
    // 輸出: [Step7] sorted: Seoul Taipei Tokyo
    // 解釋: 'S' < 'T'(字典順序)，所以Seoul排第一；Taipei與Tokyo開頭都是'T'，
    //      比較第二個字元'a'<'o'，所以Taipei排在Tokyo前面


    // 《Step8》bucket_count() 與 load_factor()
    cout<<"[Step8] bucket_count="<< visited.bucket_count() <<endl;
    cout<<"[Step8] load_factor="<< visited.load_factor() <<endl;
    // 輸出: [Step8] bucket_count=13
    // 輸出: [Step8] load_factor=0.230769
    // 計算: 目前3個元素 / 13個bucket ≈ 0.2308
    // (bucket數量13為libstdc++對「未特別指定初始大小」的unordered_set的預設值，
    //  屬於實作細節，標準並未規定固定為13)


    // 《Step9》count_if()計算城市名稱長度>5的個數
    int cnt = count_if(visited.begin(), visited.end(), [](const string& s){
        return s.size() > 5;
    });
    cout<<"[Step9] count_if(len>5)="<<cnt<<endl;
    // 輸出: [Step9] count_if(len>5)=1
    // 解釋: 目前有 "Taipei"(6字元)、"Tokyo"(5字元)、"Seoul"(5字元)，
    //      只有"Taipei"的長度(6) > 5，因此結果為1

    return 0;
}


