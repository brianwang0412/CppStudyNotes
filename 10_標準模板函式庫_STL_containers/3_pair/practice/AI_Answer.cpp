#include <iostream>
#include <vector>
#include <utility>   // pair, make_pair
#include <algorithm> // sort
#include <string>
using namespace std;

// 型別別名，讓程式碼更易讀
// Student = pair<姓名, pair<座號, 成績>>
using Student = pair<string, pair<int, double>>;

// ------------------------------------------------------------
// 第5點額外挑戰：找出成績最高的學生
// 若有並列最高分，回傳「座號最小」的那位
// ------------------------------------------------------------
pair<string, double> findTopStudent(const vector<Student>& students) {
    // 先確認 vector 不是空的（避免存取空容器造成未定義行為）
    if (students.empty()) {
        return make_pair(string(""), 0.0);
    }

    // 用第一位學生當作初始的「目前最高分」
    Student best = students[0];

    for (const auto& s : students) {
        double curScore  = s.second.second;
        double bestScore = best.second.second;
        int    curSeat   = s.second.first;
        int    bestSeat  = best.second.first;

        // 規則：成績更高 -> 更新
        //      成績相同但座號更小 -> 也要更新
        if (curScore > bestScore ||
           (curScore == bestScore && curSeat < bestSeat)) {
            best = s;
        }
    }

    // 回傳 (姓名, 成績)
    return make_pair(best.first, best.second.second);
}

int main() {
    // --------------------------------------------------------
    // 第1、2點：用 vector<pair<string, pair<int,double>>> 儲存資料
    // 這裡示範多種合法的 pair 建構方式
    // --------------------------------------------------------
    vector<Student> students;

    // 方式一：直接用 make_pair 巢狀建構
    students.push_back(make_pair("Alice", make_pair(3, 88.5)));

    // 方式二：用大括號初始化（C++11 起可用）
    students.push_back({"Bob", {1, 92.0}});

    // 方式三：用 pair 建構子直接建立
    students.push_back(Student("Cathy", pair<int, double>(2, 92.0)));

    // 方式四：混合寫法也合法
    students.push_back({"David", make_pair(5, 76.5)});

    // --------------------------------------------------------
    // 第3點：自訂排序規則
    // 重點提醒：pair 預設的 operator< 是「先比 first，再比 second」，
    // 但這裡的資料結構是 (姓名, (座號, 成績))，
    // 若直接 sort(v.begin(), v.end()) 會變成先比姓名字母順序，
    // 完全不符合題目要求！所以必須自己寫 comparator (lambda)。
    // --------------------------------------------------------
    sort(students.begin(), students.end(),
         [](const Student& a, const Student& b)  {
             double scoreA = a.second.second;
             double scoreB = b.second.second;
             int    seatA  = a.second.first;
             int    seatB  = b.second.first;

             if (scoreA != scoreB) {
                 return scoreA > scoreB; // 成績高的排前面
             }
             return seatA < seatB;       // 成績相同，座號小的排前面
         });

    // --------------------------------------------------------
    // 第4點：使用結構化綁定 (C++17) 印出排行榜
    // --------------------------------------------------------
    cout << "===== 排行榜 =====" << endl;
    int rank = 1;
    for (const auto& [name, info] : students) {
        // info 本身還是一個 pair<int, double>，可以再拆一次
        const auto& [seat, score] = info;

        cout << "第" << rank << "名: " << name
             << " (座號" << seat << ") 成績: " << score << endl;
        rank++;
    }

    // --------------------------------------------------------
    // 第5點：找出最高分學生並印出
    // --------------------------------------------------------
    cout << "\n===== 最高分學生 =====" << endl;
    auto [topName, topScore] = findTopStudent(students);
    cout << topName << " 成績: " << topScore << endl;

    return 0;
}

